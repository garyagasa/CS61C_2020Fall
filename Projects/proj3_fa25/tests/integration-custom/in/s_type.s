# s_type.s
	# 测试各类 S-type 存储指令：sb / sh / sw
	# 要求：不使用 lui，只用 addi 及移位等指令构造数据

	# 约定：
	# - 使用 s0 作为基址寄存器，指向一段测试用内存区域
	# - 使用 a0 以及若干临时寄存器回读结果，方便在 Logisim 中观察

	# s0 = 200，作为基址地址
	addi s0, x0, 200

	################################################
	# 构造一个有代表性的 32 位模式：0x00001234    #
	# 只用 addi + slli，避免使用 lui              #
	################################################

	# 确保 s1 初始化正确
	addi s1, x0, 0x123     # 0x00000123
	slli s1, s1, 4         # 0x00001230
	addi s1, s1, 4         # 0x00001234

	# 验证 sw 操作
	sw   s1, 80(s0)
	lw   a0, 80(s0)        # 验证：期望 a0 = 0x00001234

	# 验证 sh 操作
	sh   s1, 80(s0)
	lw   a1, 80(s0)        # 验证：低半字为 0x1234

	sh   s1, 82(s0)
	lw   a2, 80(s0)        # 验证：高半字被 0x1234 覆盖

	# 验证 sb 操作
	sb   s1, 80(s0)
	lw   a3, 80(s0)        # 验证：最低字节为 0x34

	sb   s1, 81(s0)
	lw   a4, 80(s0)

	sb   s1, 82(s0)
	lw   a5, 80(s0)

	sb   s1, 83(s0)
	lw   a6, 80(s0)

	########################################
	#            负偏移地址测试            #
	########################################

	# 再构造一个全 1 模式，测试在负偏移处的部分写入
	addi t0, x0, -1        # 0xFFFFFFFF

	# sw：在负偏移地址处写入全 1
	sw   t0, -204(s0)
	lw   a0, -204(s0)      # 期望：0xFFFFFFFF

	# sh：只覆盖低半字
	sh   s1, -204(s0)
	lw   t1, -204(s0)

	# sh：只覆盖高半字
	sh   s1, -202(s0)
	lw   t2, -204(s0)

	# sb：依次覆盖 4 个字节的最低 8 位
	sb   s1, -204(s0)
	lw   t0, -204(s0)

	sb   s1, -203(s0)
	lw   t1, -204(s0)

	sb   s1, -202(s0)
	lw   t2, -204(s0)

	sb   s1, -201(s0)
	lw   a0, -204(s0)

	# 程序结束（不要自旋，以免 Venus 认为程序死循环)